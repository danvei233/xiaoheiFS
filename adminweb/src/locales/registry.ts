export function matchLanguage(value: string): LanguageEnum | undefined {
  const tag = value.toLowerCase().replace(/_/g, '-')
  if (/^zh-(tw|hk|mo|hant)(-|$)/.test(tag)) return LanguageEnum.ZH_TW
  return (
    languageOptions.find((item) => item.value.toLowerCase() === tag)?.value ??
    languageOptions.find((item) => item.value === tag.split('-')[0])?.value
  )
}

export function browserLanguage(): LanguageEnum {
  for (const tag of navigator.languages?.length
    ? navigator.languages
    : [navigator.language || 'en']) {
    const language = matchLanguage(tag)
    if (language) return language
  }
  return LanguageEnum.EN
}

